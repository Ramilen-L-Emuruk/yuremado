/** 韓国語の辞書。気象庁の多言語辞書にある語はそれに合わせ、無い語は作った（語ごとの出どころは `docs/spec/i18n-spec.md` §4）。 */
/**
 * 主題の助詞（은/는）を、差し込む語の最後の音で選んで付ける。最後の文字がハングルで終声（받침）があれば 은、
 * 無ければ 는。ハングル以外で終わる語（英数字・記号）は、読みが決められないので 는 にする。
 */
function withTopic(word: string): string {
  const last = word.trimEnd().codePointAt(word.trimEnd().length - 1) ?? 0
  const hangul = last >= 0xac00 && last <= 0xd7a3
  return `${word}${hangul && (last - 0xac00) % 28 !== 0 ? '은' : '는'}`
}

